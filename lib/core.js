export function phoneNumber(input) {
  const raw=String(input??'').trim();
  if(!raw || !/^[+\d\s().-]+$/.test(raw)) return null;
  let n=raw.replace(/\D/g,'');
  if(n.startsWith('0')) n='62'+n.slice(1);
  if(n.startsWith('8')) n='62'+n;
  return /^62\d{8,13}$/.test(n)?n:null;
}
export function mobileNumber(n) { return /^628\d{7,12}$/.test(n??''); }
const tidy=(x,max=300)=>String(x??'').trim().slice(0,max);
export function normalizeLead(row) {
  if(!row || typeof row!=='object') throw Error('Lead tidak valid');
  const name=tidy(row.name,160), phone=phoneNumber(row.phone), email=tidy(row.email,254).toLowerCase();
  if(!name || (!phone&&!email)) throw Error('Nama dan minimal satu kontak diperlukan');
  if(email&&!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) throw Error('Email tidak valid');
  const num=Number(row.priority??50);
  const priority=Number.isFinite(num)?Math.max(0,Math.min(100,Math.round(num))):50;
  let source=tidy(row.source,1000);
  if(source&&!/^https?:\/\/[^\s]+$/i.test(source)) throw Error('Sumber harus URL HTTP(S)');
  return {name,key:name.toLowerCase().replace(/\s+/g,' '),phone,email:email||null,category:tidy(row.category,80),location:tidy(row.location,160),source,priority};
}
